global KMemcpy
global KMemset
global FillScreen
global RoundInt
RoundInt:
	PUSH EBP
	MOV EBP,ESP
	PUSH ECX
	MOV ECX,0x4000
	FILD DWORD [EBP+8]
	FRNDINT
	FISTP DWORD [ECX]
	MOV DWORD EAX,[ECX]
	POP ECX
	POP EBP
	RET

KMemcpy:
	PUSH EBP
	MOV EBP,ESP
	PUSH ESI
	PUSH EDI
	PUSH ECX
	MOV DWORD ESI,[EBP+8]
	MOV DWORD EDI,[ESP+12]
	MOV EAX,EDI
	MOV DWORD ECX,[ESP+16]
	REP MOVSB
	POP ECX
	POP EDI
	POP ESI
	POP EBP
	RET
KMemset:
	;Slow
	PUSH EBP
	MOV EBP,ESP
	MOV DWORD EDI,[EBP+8]
	MOV BYTE AL,[EBP+12]
	MOV DWORD ECX,[EBP+16]
	REP STOSB
	POP EBP
	RET
KMemsetU16:
	PUSH EBP
	MOV EBP,ESP
	MOV DWORD EDI,[EBP+8]
	MOV BYTE AL,[EBP+12]
	MOV DWORD ECX,[EBP+16]
	REP STOSW
	POP EBP
	RET
KMemsetU32:
	PUSH EBP
	MOV EBP,ESP
	MOV DWORD EDI,[EBP+8]
	MOV BYTE AL,[EBP+12]
	MOV DWORD ECX,[EBP+16]
	REP STOSD
	POP EBP
	RET
FillScreen:
	MOV AX,5
	MOV ECX,0xFFFF
	MOV EDI,0xA0000
	REP STOSB
	RET
