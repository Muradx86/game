global OutU8
global OutU16
global InU8
global InU16
OutU8:
	PUSH EBP
	MOV EBP,ESP
	MOV WORD DX,[EBP+8]
	MOV BYTE AL,[EBP+12]
	OUT DX,AL
	POP EBP
	RET
OutU16:
	PUSH EBP
	MOV EBP,ESP
	MOV WORD DX,[EBP+8]
	MOV WORD AX,[EBP+12]
	OUT DX,AX
	POP EBP
	RET
InU8:
	PUSH EBP
	MOV EBP,ESP
	MOV WORD DX,[EBP+8]
	IN AL,DX
	MOVZX EAX,AL
	POP EBP
	RET
InU16:
	PUSH EBP
	MOV EBP,ESP
	MOV WORD DX,[EBP+8]
	IN AX,DX
	MOVZX EAX,AX
	POP EBP
	RET
