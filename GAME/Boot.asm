BITS 16
ORG 0x7C00
FUN_MAIN:
	XOR EAX,EAX
	MOV DS,AX
	MOV SS,AX
	MOV SP,0x9000
	MOV AX,0x1000
	MOV ES,AX
	XOR EBX,EBX
	MOV AX,0x13
	INT 0x10
	;A20
	IN AL,0x92
	OR AL,2
	OUT 0x92,AL
	MOV DH,0
	MOV CH,0
	MOV CL,2
	MOV AL,50
	MOV DL,0x80
	MOV AH,2
	INT 0x13
	JC DISK_ERROR
	LGDT [BHDD_DESCRIPT_GDT]
	MOV EAX,CR0
	BTS EAX,0
	MOV CR0,EAX
	JMP 0x8:START32
BITS 32
START32:
	XOR EAX,EAX
	MOV AX,0x10
	MOV ES,AX
	MOV SS,AX
	MOV ESP,0x9000
	MOV DS,AX
	MOV FS,AX
	MOV GS,AX
	JMP 0x10000
DISK_ERROR:
	MOV AX,0xA000
	MOV ES,AX
	XOR BX,BX
	MOV BYTE [ES:BX],1 ;DARK BLUE
.HALT:
	HLT
	JMP .HALT
	
BHDD_GDT_START:
	DQ 0

	DW 0xFFFF			;limit quad
	DW 0			;base quad
	DB 0				;base byte
	DB 0x9A				;type byte
	DB 0xCF				;flags
	DB 0				;base byte
	
	DW 0xFFFF			;limit quad
	DW 0			;base quad
	DB 0				;base byte
	DB 0x92				;type byte		
	DB 0xCF				;flags
	DB 0
BHDD_GDT_END:
BHDD_DESCRIPT_GDT:
	DW BHDD_GDT_END - BHDD_GDT_START - 1
	DD BHDD_GDT_START
	
TIMES 510-($-$$) DB 0
DW 0xAA55
